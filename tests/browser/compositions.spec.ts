import { expect, test } from "@playwright/test";

test("desktop composition editor renders and persists an end-to-end local workflow", async ({ page, request }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.getByRole("button", { name: "图文管理", exact: true }).click();
  await expect(page.locator(".composition-photo")).toHaveCount(8);
  await expect(page.getByLabel("图文组标题")).toHaveValue("海边与街巷的两日小记");
  await expect(page.locator(".composition-source-photo")).toHaveCount(12);
  await expect(page.locator(".composition-presets button")).toHaveCount(9);
  const initialGroup = (await (await request.get("/api/compositions")).json()).groups[0];
  await expect(page.locator(".composition-directory code")).toHaveText(initialGroup.directory);
  await expect(page.locator(".composition-photo-strength input")).toHaveCount(8);
  await expect(page.locator(".composition-filter input[type='range']")).toHaveCount(0);
  await page.getByTitle("填入地点：外滩", { exact: true }).click();
  await expect(page.getByLabel("图文组地点")).toHaveValue("滨海步道，街巷与公园，外滩");
  await expect(page.getByTitle("填入地点：街巷", { exact: true })).toBeVisible();
  await expect(page.getByTitle("填入地点：外滩、街巷", { exact: true })).toHaveCount(0);
  await page.locator(".composition-photo img").first().waitFor();
  await page.locator(".composition-workspace img").evaluateAll(images => images.forEach(image => (image as HTMLImageElement).loading = "eager"));
  await page.waitForFunction(() => [...document.querySelectorAll<HTMLImageElement>(".composition-workspace img")].every(image => image.complete && image.naturalWidth > 0));
  for (const width of [1100, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.screenshot({ path: `.pytest_tmp/compositions-${width}.png`, fullPage: true });
    const problems = await page.evaluate(() => {
      const bounds = [...document.querySelectorAll<HTMLElement>(".composition-heading button, .composition-metadata input, .composition-readonly strong, .composition-date-list label, .composition-presets button")];
      return bounds.filter(element => element.scrollWidth > element.clientWidth + 2).map(element => element.className || element.tagName);
    });
    expect(problems).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    const image = await page.locator(".composition-photo-select").first().boundingBox();
    const inspector = await page.locator(".composition-inspector").boundingBox();
    expect(image!.x + image!.width).toBeLessThan(inspector!.x);
    const copy = await page.getByLabel("文案标题", { exact: true }).boundingBox();
    expect(copy!.width).toBeGreaterThanOrEqual(width <= 1260 ? 320 : 375);
    const preset = await page.locator(".composition-presets img").first().boundingBox();
    expect(preset!.width).toBeGreaterThanOrEqual(width <= 1260 ? 94 : 110);
    const grid = await page.locator(".composition-presets").evaluate(element => {
      const tiles = [...element.children].map(tile => tile.getBoundingClientRect());
      const bounds = element.getBoundingClientRect();
      return { rows: new Set(tiles.map(tile => Math.round(tile.top))).size,
        columns: new Set(tiles.map(tile => Math.round(tile.left))).size,
        fits: element.scrollHeight <= element.clientHeight + 1 && tiles.every(tile => tile.bottom <= bounds.bottom + 1) };
    });
    expect(grid).toEqual({ rows: 3, columns: 3, fits: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator(".composition-presets").getByRole("button", { name: "暖调胶片", exact: true }).click();
  await page.getByLabel("第 1 张滤镜强度", { exact: true }).fill("65");
  await page.getByTitle("选中第 2 张图片", { exact: true }).click();
  await expect(page.locator(".annotation-lightbox")).toHaveCount(0);
  await page.locator(".composition-presets").getByRole("button", { name: "青橙电影", exact: true }).click();
  await expect(page.locator(".composition-photo img").nth(1)).toHaveAttribute("src", /preset=cinema/);
  await page.locator(".composition-presets").getByRole("button", { name: "森系青绿", exact: true }).click();
  await page.getByLabel("第 2 张滤镜强度", { exact: true }).fill("30");
  await expect(page.locator(".composition-photo img").first()).toHaveAttribute("src", /preset=warm-film&strength=65/);
  await expect(page.locator(".composition-photo img").nth(1)).toHaveAttribute("src", /preset=forest&strength=30/);
  await page.getByTitle("选中第 1 张图片", { exact: true }).click();
  await expect(page.locator(".composition-presets").getByRole("button", { name: "暖调胶片", exact: true })).toHaveAttribute("aria-pressed", "true");
  const src = await page.locator(".composition-photo img").first().getAttribute("src");
  const original = await request.get(src!.replace("preset=warm-film", "preset=original"));
  const filtered = await request.get(src!);
  expect(Buffer.compare(await original.body(), await filtered.body())).not.toBe(0);
  await page.getByTitle("放大第 1 张图片", { exact: true }).click();
  await expect(page.locator(".annotation-lightbox > img")).toBeVisible();
  await expect(page.locator(".annotation-lightbox > img")).toHaveAttribute("src", /preset=warm-film/);
  const controls = page.locator(".annotation-lightbox-controls");
  await expect(controls.locator(".composition-presets button")).toHaveCount(9);
  for (const width of [1100, 1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.locator(".annotation-lightbox > img")).not.toHaveClass(/pending/);
    await expect(controls.locator("img").last()).toBeVisible();
    await page.waitForFunction(() => [...document.querySelectorAll<HTMLImageElement>(".annotation-lightbox img")].every(image => image.complete && image.naturalWidth > 0));
    const image = await page.locator(".annotation-lightbox > img").boundingBox();
    const panel = await controls.boundingBox();
    const slider = await page.getByLabel("大图滤镜强度").boundingBox();
    expect(image!.x + image!.width).toBeLessThan(panel!.x);
    expect(slider!.x + slider!.width).toBeLessThanOrEqual(width);
    expect(slider!.y + slider!.height).toBeLessThanOrEqual(1000);
    expect(await controls.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: `.pytest_tmp/compositions-lightbox-${width}.png` });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await controls.getByRole("button", { name: "黑白纪实", exact: true }).click();
  await page.getByLabel("大图滤镜强度").fill("55");
  await expect(page.locator(".annotation-lightbox > img")).toHaveAttribute("src", /preset=mono&strength=55/);
  await expect(page.locator(".composition-photo img").first()).toHaveAttribute("src", /preset=mono&strength=55/);
  await controls.getByRole("button", { name: "暖调胶片", exact: true }).click();
  await page.getByLabel("大图滤镜强度").fill("65");
  await expect(page.locator(".annotation-lightbox > img")).toHaveAttribute("src", /preset=warm-film&strength=65/);
  await page.screenshot({ path: ".pytest_tmp/compositions-lightbox.png" });
  await page.getByTitle("关闭大图", { exact: true }).focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.locator(".annotation-lightbox-heading")).toContainText("2 / 8");
  await expect(page.getByLabel("大图滤镜强度")).toHaveValue("30");
  await expect(controls.getByRole("button", { name: "森系青绿", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByLabel("大图滤镜强度").focus();
  await page.keyboard.press("ArrowRight");
  await expect(page.getByLabel("大图滤镜强度")).toHaveValue("31");
  await expect(page.locator(".annotation-lightbox-heading")).toContainText("2 / 8");
  await page.getByLabel("大图滤镜强度").fill("30");
  await expect(page.locator(".annotation-lightbox > img")).toHaveAttribute("src", /preset=forest&strength=30/);
  await page.keyboard.press("Escape");
  await expect(page.locator(".annotation-lightbox")).toHaveCount(0);
  const originalOrder = await page.locator(".composition-photo").evaluateAll(photos => photos.map(photo => photo.getAttribute("data-photo-id")));
  const last = await page.locator(".composition-photo").last().boundingBox();
  await page.locator(".composition-photo-select").first().dragTo(page.locator(".composition-photo").last(), { targetPosition: { x: last!.width - 5, y: 40 } });
  await expect(page.locator(".composition-photo").last()).toHaveAttribute("data-photo-id", originalOrder[0]!);
  await expect(page.locator(".composition-photo.active")).toHaveAttribute("data-photo-id", originalOrder[0]!);
  await expect(page.locator(".composition-photo img").last()).toHaveAttribute("src", /preset=warm-film&strength=65/);
  await page.locator(".composition-photo-select").last().dragTo(page.locator(".composition-photo").first(), { targetPosition: { x: 5, y: 40 } });
  expect(await page.locator(".composition-photo").evaluateAll(photos => photos.map(photo => photo.getAttribute("data-photo-id")))).toEqual(originalOrder);
  const third = await page.locator(".composition-photo").nth(2).boundingBox();
  await page.locator(".composition-photo-select").first().dragTo(page.locator(".composition-photo").nth(2), { targetPosition: { x: third!.width - 5, y: 40 } });
  const reordered = [originalOrder[1], originalOrder[2], originalOrder[0], ...originalOrder.slice(3)];
  expect(await page.locator(".composition-photo").evaluateAll(photos => photos.map(photo => photo.getAttribute("data-photo-id")))).toEqual(reordered);
  await expect(page.locator(".annotation-lightbox")).toHaveCount(0);
  await page.screenshot({ path: ".pytest_tmp/compositions-sorted.png", fullPage: true });
  await page.getByLabel("文案标题", { exact: true }).fill("手写文案标题");
  await page.getByLabel("文案正文").fill("沿着海边走走，再去街巷里看看。合成数据，仅用于测试。");
  await page.getByRole("button", { name: "照片标注", exact: true }).click();
  await page.getByRole("button", { name: "图文管理", exact: true }).click();
  await expect(page.getByLabel("文案正文")).toHaveValue(/合成数据，仅用于测试/);
  expect(await page.locator(".composition-photo").evaluateAll(photos => photos.map(photo => photo.getAttribute("data-photo-id")))).toEqual(reordered);
  await expect(page.locator(".composition-photo img").first()).toHaveAttribute("src", /preset=forest&strength=30/);
  await expect(page.locator(".composition-photo img").nth(2)).toHaveAttribute("src", /preset=warm-film&strength=65/);
  await page.getByRole("button", { name: "保存图文组", exact: true }).click();
  await expect(page.locator(".composition-message")).toContainText("图文组已保存");
  await page.reload();
  await page.getByRole("button", { name: "图文管理", exact: true }).click();
  await expect(page.getByLabel("文案正文")).toHaveValue(/合成数据，仅用于测试/);
  expect(await page.locator(".composition-photo").evaluateAll(photos => photos.map(photo => photo.getAttribute("data-photo-id")))).toEqual(reordered);
  await expect(page.locator(".composition-photo img").first()).toHaveAttribute("src", /preset=forest&strength=30/);
  await expect(page.locator(".composition-photo img").nth(2)).toHaveAttribute("src", /preset=warm-film&strength=65/);
  await page.getByRole("button", { name: "准备文案", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Agent 文案任务" })).toBeVisible();
  await expect(page.getByLabel("Agent 指令")).toHaveValue(/agent-request.md/);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog", { name: "Agent 文案任务" })).toHaveCount(0);
  await page.getByRole("button", { name: "新建", exact: true }).click();
  await expect(page.locator(".composition-directory")).toContainText("尚未保存");
  await expect(page.locator(".composition-directory code")).toHaveCount(0);
  await page.getByLabel("搜索精选日期").fill("2024-05-02");
  await page.locator(".composition-date-list input").check();
  await expect(page.locator(".composition-source-photo")).toHaveCount(6);
  await page.locator(".composition-source-photo > button:first-child").first().click();
  await expect(page.getByLabel("图文城市", { exact: true })).toHaveValue("深圳");
  await expect(page.getByLabel("时间自动填写")).toBeChecked();
  await expect(page.getByLabel("城市自动填写")).toBeChecked();
  await page.getByLabel("时间自动填写").uncheck();
  await page.getByLabel("城市自动填写").uncheck();
  await page.getByLabel("图文开始日期").fill("2024-06-01");
  await page.getByLabel("图文结束日期").fill("2024-06-03");
  await page.getByLabel("图文城市", { exact: true }).fill("杭州，南京");
  await page.getByLabel("图文组标题").fill("单日图文");
  await page.getByLabel("图文组地点").fill("海边");
  await page.getByRole("button", { name: "保存图文组", exact: true }).click();
  await expect(page.locator(".composition-message")).toContainText("图文组已保存");
  await expect(page.locator(".composition-group")).toHaveCount(2);
  const newGroup = (await (await request.get("/api/compositions")).json()).groups[0];
  await expect(page.locator(".composition-directory code")).toHaveText(newGroup.directory);
  expect(newGroup.directory).not.toBe(initialGroup.directory);
  await page.reload();
  await page.getByRole("button", { name: "图文管理", exact: true }).click();
  await expect(page.getByLabel("时间自动填写")).not.toBeChecked();
  await expect(page.getByLabel("城市自动填写")).not.toBeChecked();
  await expect(page.getByLabel("图文开始日期")).toHaveValue("2024-06-01");
  await expect(page.getByLabel("图文城市", { exact: true })).toHaveValue("杭州，南京");
  await expect(page.locator(".composition-directory code")).toHaveText(newGroup.directory);
  await page.locator(".composition-date-list label").filter({ hasText: "2024-05-03" }).locator("input").check();
  await expect(page.getByLabel("时间自动填写")).toBeChecked();
  await expect(page.getByLabel("城市自动填写")).toBeChecked();
  await expect(page.getByLabel("图文开始日期")).toHaveValue("2024-05-02");
  await expect(page.getByLabel("图文结束日期")).toHaveValue("2024-05-03");
  await expect(page.getByLabel("图文城市", { exact: true })).toHaveValue("上海，深圳");
  await page.getByTitle("删除图文组", { exact: true }).click();
  await page.getByRole("dialog", { name: "删除图文组", exact: true }).getByRole("button", { name: "删除", exact: true }).click();
  await expect(page.locator(".composition-group")).toHaveCount(1);
  expect(errors).toEqual([]);
});
